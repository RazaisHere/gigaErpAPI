-- Giga Workspace — PostgreSQL schema (Supabase)
-- Workspace-owned tables only. ERP src_* views stay on MySQL.

CREATE TABLE IF NOT EXISTS roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL,
  name VARCHAR(80) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT roles_code_unique UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  code VARCHAR(10) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT departments_code_unique UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  cognito_sub VARCHAR(36) NULL,
  password VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NULL,
  employee_code VARCHAR(20) NULL,
  face_image VARCHAR(255) NULL,
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(30) NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT users_email_unique UNIQUE (email),
  CONSTRAINT users_cognito_sub_unique UNIQUE (cognito_sub),
  CONSTRAINT users_employee_code_unique UNIQUE (employee_code)
);

CREATE TABLE IF NOT EXISTS user_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id),
  role_id BIGINT NOT NULL REFERENCES roles (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT user_roles_pair_unique UNIQUE (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS user_roles_role_id ON user_roles (role_id);

CREATE TABLE IF NOT EXISTS department_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id),
  department_id BIGINT NOT NULL REFERENCES departments (id),
  is_admin BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT department_users_pair_unique UNIQUE (user_id, department_id)
);
CREATE INDEX IF NOT EXISTS department_users_department_id ON department_users (department_id);

CREATE TABLE IF NOT EXISTS client_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL REFERENCES users (id),
  source_client_id INTEGER NOT NULL,
  verification_status VARCHAR(40) NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT client_links_source_unique UNIQUE (source_client_id),
  CONSTRAINT client_links_user_unique UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS pending_client_signups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  cnic VARCHAR(20) NOT NULL,
  source_client_id INTEGER NOT NULL,
  client_name VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pending_client_signups_email_unique UNIQUE (email)
);
CREATE INDEX IF NOT EXISTS pending_client_signups_source ON pending_client_signups (source_client_id);

CREATE TABLE IF NOT EXISTS case_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  default_department_id BIGINT NOT NULL REFERENCES departments (id),
  default_sla_hours INTEGER NOT NULL DEFAULT 48,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT case_categories_name_unique UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS sla_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  priority VARCHAR(20) NOT NULL,
  target_hours INTEGER NOT NULL,
  escalate_at_percent SMALLINT NOT NULL DEFAULT 80,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT sla_rules_priority_unique UNIQUE (priority)
);

CREATE TABLE IF NOT EXISTS handoff_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_department_id BIGINT NOT NULL REFERENCES departments (id),
  to_department_id BIGINT NOT NULL REFERENCES departments (id),
  is_allowed BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT handoff_rules_pair_unique UNIQUE (from_department_id, to_department_id)
);

CREATE TABLE IF NOT EXISTS cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_no VARCHAR(30) NOT NULL,
  source_client_id INTEGER NULL,
  source_unitsale_id INTEGER NULL,
  source_unit_id INTEGER NULL,
  source_receipt_id INTEGER NULL,
  category_id BIGINT NOT NULL REFERENCES case_categories (id),
  department_id BIGINT NOT NULL REFERENCES departments (id),
  assignee_user_id BIGINT NULL REFERENCES users (id),
  status VARCHAR(40) NOT NULL DEFAULT 'New',
  priority VARCHAR(20) NOT NULL DEFAULT 'Normal',
  sla_band VARCHAR(20) NOT NULL DEFAULT 'On track',
  opened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  closed_at TIMESTAMPTZ NULL,
  created_by BIGINT NULL REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT cases_case_no_unique UNIQUE (case_no)
);
CREATE INDEX IF NOT EXISTS cases_department_status ON cases (department_id, status);
CREATE INDEX IF NOT EXISTS cases_source_client ON cases (source_client_id);
CREATE INDEX IF NOT EXISTS cases_source_unitsale ON cases (source_unitsale_id);
CREATE INDEX IF NOT EXISTS cases_assignee ON cases (assignee_user_id);

CREATE TABLE IF NOT EXISTS case_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id BIGINT NOT NULL REFERENCES cases (id),
  user_id BIGINT NOT NULL REFERENCES users (id),
  body TEXT NOT NULL,
  client_visible BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS case_notes_case_id ON case_notes (case_id);

CREATE TABLE IF NOT EXISTS case_handoffs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id BIGINT NOT NULL REFERENCES cases (id),
  from_department_id BIGINT NOT NULL REFERENCES departments (id),
  to_department_id BIGINT NOT NULL REFERENCES departments (id),
  by_user_id BIGINT NOT NULL REFERENCES users (id),
  note VARCHAR(500) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS case_handoffs_case_id ON case_handoffs (case_id);

CREATE TABLE IF NOT EXISTS notification_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  template_key VARCHAR(80) NOT NULL,
  channel VARCHAR(20) NOT NULL,
  subject VARCHAR(255) NULL,
  body TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT notification_templates_key_unique UNIQUE (template_key)
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL,
  role_code VARCHAR(40) NULL,
  department_id BIGINT NULL,
  action VARCHAR(80) NOT NULL,
  module VARCHAR(80) NOT NULL,
  subject_type VARCHAR(80) NULL,
  subject_id BIGINT NULL,
  ip VARCHAR(45) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS audit_logs_created_at ON audit_logs (created_at);
CREATE INDEX IF NOT EXISTS audit_logs_module_action ON audit_logs (module, action);
